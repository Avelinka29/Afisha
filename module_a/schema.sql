CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 faculty VARCHAR(190) NOT NULL, course TINYINT UNSIGNED NOT NULL, avatar_url VARCHAR(1000) NULL,
 role ENUM('student','admin') NOT NULL DEFAULT 'student', email_verified_at DATETIME NULL,
 blocked BOOLEAN NOT NULL DEFAULT FALSE, auth_version INT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS clubs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL, description TEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS google_accounts (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 google_sub VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS club_users (
 user_id BIGINT UNSIGNED NOT NULL, club_id BIGINT UNSIGNED NOT NULL, verified BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY (user_id, club_id), FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (club_id) REFERENCES clubs(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 club_id BIGINT UNSIGNED NOT NULL, category_id BIGINT UNSIGNED NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL, description TEXT NOT NULL, starts_at DATETIME NOT NULL, ends_at DATETIME NOT NULL,
 location VARCHAR(1000) NOT NULL, format ENUM('offline','online') NOT NULL, capacity INT UNSIGNED NULL, cover_url VARCHAR(1000) NULL,
 status ENUM('draft','published','cancelled') NOT NULL DEFAULT 'draft', cancellation_reason TEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX (status, starts_at), FOREIGN KEY (club_id) REFERENCES clubs(id), FOREIGN KEY (category_id) REFERENCES categories(id), FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS registrations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, event_id BIGINT UNSIGNED NOT NULL,
 status ENUM('active','cancelled_by_organizer') NOT NULL DEFAULT 'active', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY (user_id, event_id), FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reactions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, event_id BIGINT UNSIGNED NOT NULL,
 type ENUM('like','interested') NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY (user_id, event_id, type), FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, type VARCHAR(60) NOT NULL,
 payload JSON NOT NULL, message TEXT NOT NULL, read_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id), INDEX (user_id, created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS auth_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 purpose ENUM('verify','reset') NOT NULL, expires_at DATETIME NOT NULL, FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reminder_deliveries (
 event_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL, reminder_hours INT NOT NULL, starts_at DATETIME NOT NULL,
 PRIMARY KEY (event_id, user_id, reminder_hours, starts_at), FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE, FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
